// Optional browser check (not part of npm test): needs Playwright, the app on http://localhost:8080 and sample .tcx files in /tmp/coros/tcx.
const { chromium } = require('playwright');
(async () => {
  const browser = await chromium.launch();
  const ctx = await browser.newContext({ viewport: { width: 1000, height: 1000 }, timezoneId: 'Asia/Bangkok' });
  const page = await ctx.newPage();
  page.on('pageerror', (e) => console.log('pageerror', e.message));
  page.on('console', (m) => { if (m.type() === 'error') console.log('console', m.text()); });
  await page.goto('http://localhost:8080/index.html#history');
  await page.waitForSelector('#hist-files');
  await page.setInputFiles('#hist-files', ['/tmp/coros/tcx/2026-11-04.tcx', '/tmp/coros/tcx/2026-11-08.tcx']);
  await page.waitForSelector('.results li'); await page.waitForTimeout(600);
  const txt = async () => (await page.textContent('#page-history')).replace(/\s+/g, ' ');
  const row = async () => (await page.locator('table.list tbody tr').first().textContent()).replace(/\s+/g, ' ');
  console.log('before :', await row());
  console.log('weekly climbing before:', (await txt()).match(/Weekly climbing\d+ m/)?.[0]);
  await page.locator('[data-climb]').first().click();
  await page.waitForSelector('#climb-editor');
  console.log('splits :', await page.locator('[data-climb-val]').count());
  await page.fill('[data-climb-fill]', '3'); await page.click('[data-climb-do="fill"]');
  await page.locator('[data-climb-val]').nth(2).fill('10');
  console.log('live   :', await page.textContent('#climb-total'));
  await page.screenshot({ path: '/tmp/shots/climb_editor.png', fullPage: true });
  await page.selectOption('[data-climb-unit]', 'm');
  console.log('as m   :', await page.textContent('#climb-total'), '| split 3 =', await page.locator('[data-climb-val]').nth(2).inputValue());
  await page.locator('[data-climb-val]').nth(0).fill('999'); await page.click('[data-climb-do="save"]');
  console.log('error  :', (await txt()).match(/One split cannot[^.]*\./)?.[0]);
  await page.locator('[data-climb-val]').nth(0).fill('30'); await page.click('[data-climb-do="save"]');
  await page.waitForTimeout(500);
  console.log('after  :', await row());
  console.log('weekly climbing after:', (await txt()).match(/Weekly climbing\d+ m/)?.[0]);
  await page.reload(); await page.waitForTimeout(800);
  console.log('reload :', await row());
  await page.locator('[data-climb]').first().click(); await page.waitForSelector('#climb-editor');
  console.log('reopen : unit', await page.locator('[data-climb-unit]').inputValue(), 'split1', await page.locator('[data-climb-val]').nth(0).inputValue());
  await page.click('[data-climb-do="reset"]'); await page.waitForTimeout(500);
  console.log('reset  :', await row());
  await browser.close();
})();
